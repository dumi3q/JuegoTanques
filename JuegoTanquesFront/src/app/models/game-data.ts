// ================= INTERFACES (Estructuras) =================

export interface Tanque {
  tanque_id: string;
  nombre: string;
  vida_base: number;
  velocidad_base: number;
  blindaje: number;
  precio: number;
  imagen: string;
  habilidades: string[];
}

export interface Arma {
  arma_id: string;
  nombre: string;
  danio_base: number;
  cadencia_fuego: string;
  velocidad_proyectil: number;
  precio: number;
  imagen: string; // <-- Campo para la ruta del PNG de la carpeta armas
}

export interface PowerUpNerf {
  id: string;
  nombre: string;
  tipo: 'power-up' | 'nerf';
  efecto: string;
  valor: number;
  imagen: string;
}

export interface MapaJuego {
  id: string;
  nombre: string;
  estilo: string;
  imagen: string;
  filas: number;
  columnas: number;
  matrizColisiones: number[][]; // 0 para camino libre, 1 para paredes/obstáculos
}

