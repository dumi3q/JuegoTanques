// ================= INTERFACES (Estructuras) =================
export interface Tanque {
  tanque_id: string;
  nombre: string;
  vida_base: number;
  velocidad_base: number;
  blindaje: number;
  precio: number;
  imagenTienda: string; // Arte en perspectiva para la tienda
  imagenJuego: string;  // Sprite Top-Down para el mapa de juego
  habilidades: string[];
}

export interface Arma {
  arma_id: string;
  nombre: string;
  danio_base: number;
  cadencia_fuego: string;
  velocidad_proyectil: number;
  precio: number;
  imagen: string;
}

export interface PowerUpNerf {
  id: string;
  nombre: string;
  tipo: 'power-up' | 'nerf';
  efecto: string;
  valor: number;
  imagen: string;
}

export interface MapaJuego {
  id: string;
  nombre: string;
  tipo?: string;
  descripcion: string;
  matrizColisiones: number[][];
  imagen?: string;  // Opcional para evitar el error en salas
  estilo?: string;  // Opcional para evitar el error en salas
}
